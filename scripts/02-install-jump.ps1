# 02-install-jump.ps1 -- the box-local jump key, plus jump.ps1 (the ForceCommand wrapper).
# The jump key lets the local admin hop to the session server on 127.0.0.1. It never leaves
# this PC, and the session server accepts it only from 127.0.0.1 / ::1. (The hop doesn't rely
# on SSH agent forwarding through Windows OpenSSH.)
# Needs the session server from 01 running. Safe to re-run.
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot\config.ps1"
Assert-Config

# 1. Jump key, without a passphrase: jump.ps1 uses it unattended.
New-Item -ItemType Directory -Force -Path (Split-Path $JumpKey) | Out-Null
if (-not (Test-Path $JumpKey)) {
    & (Join-Path $OpenSshBin 'ssh-keygen.exe') -q -t ed25519 -C "jump $AdminUser to $EntraUser" -f $JumpKey -N '""'
    if ($LASTEXITCODE -ne 0) { throw 'ssh-keygen failed' }
}

# 2. Trust it in the session server, from localhost only.
$pub  = (Get-Content "$JumpKey.pub" -Raw).Trim()
$blob = $pub.Split(' ')[1]
$ak   = Join-Path $SessionDir 'authorized_keys'
if (-not ((Get-Content $ak -Raw) -match [regex]::Escape($blob))) {
    Add-Content -Path $ak -Value ('from="127.0.0.1,::1" ' + $pub) -Encoding ascii
}

# 3. jump.ps1 -- 03 makes this the ForceCommand for every login by the local admin.
$template = @'
# jump.ps1 -- ForceCommand for __ADMIN__ (generated by 02-install-jump.ps1).
# Hops every __ADMIN__ login into __ENTRA__'s own desktop session: the sshd on
# 127.0.0.1:__PORT__ that runs as that user, elevated, started by a logon task.
# If that server isn't running (user logged off), stays as __ADMIN__ so nobody is locked out.
$ssh  = '__BIN__\ssh.exe'
$key  = '__KEY__'
$orig = $env:SSH_ORIGINAL_COMMAND

# scp/sftp: serve locally as __ADMIN__
if ($orig -match 'sftp-server|internal-sftp') {
    & '__BIN__\sftp-server.exe'
    exit $LASTEXITCODE
}

$up = $false
$c = New-Object System.Net.Sockets.TcpClient
try { $up = $c.ConnectAsync('127.0.0.1', __PORT__).Wait(1000) } catch { $up = $false }
$c.Close()

if (-not $up) {
    [Console]::Error.WriteLine('Session server on port __PORT__ is not running (user logged off?). Staying as __ADMIN__.')
    if ($orig) {
        $enc = [Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($orig))
        & powershell.exe -NoProfile -EncodedCommand $enc
        exit $LASTEXITCODE
    }
    & powershell.exe -NoLogo
    exit $LASTEXITCODE
}

$opts = @('-i', $key, '-p', '__PORT__', '-o', 'StrictHostKeyChecking=accept-new', '-o', 'BatchMode=yes', '-o', 'LogLevel=ERROR')
if ($orig) {
    # The command is encoded exactly once, here. Send plain text to this wrapper: a command that
    # is itself a `powershell -EncodedCommand ...` ends up double-encoded, which Defender kills.
    $enc = [Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($orig))
    & $ssh @opts '__ENTRA__@127.0.0.1' "powershell -NoProfile -EncodedCommand $enc"
} else {
    & $ssh -t @opts '__ENTRA__@127.0.0.1'
}
exit $LASTEXITCODE
'@
$jump = $template.Replace('__ADMIN__', $AdminUser)
$jump = $jump.Replace('__ENTRA__', $EntraUser)
$jump = $jump.Replace('__PORT__', [string]$SessionPort)
$jump = $jump.Replace('__KEY__', $JumpKey)
$jump = $jump.Replace('__BIN__', $OpenSshBin)
Set-Content -Path $JumpScript -Value $jump -Encoding ascii
"wrote $JumpScript"

# 4. Prove the hop works before 03 wires it to logins.
$check = 'whoami; ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)'
& (Join-Path $OpenSshBin 'ssh.exe') -i $JumpKey -p $SessionPort -o StrictHostKeyChecking=accept-new `
    -o BatchMode=yes -o LogLevel=ERROR "$EntraUser@127.0.0.1" $check
if ($LASTEXITCODE -ne 0) { throw 'The hop failed. Is the session server from 01 running?' }
'Hop OK: expect the Entra user above, then True (elevated).'
